"""Build the synthetic corpus stale is measured on.

THE CORPUS IS INVENTED. There is no public archive of one person's notes,
and borrowing somebody else's would be both a privacy problem and a
licensing one, so every note, every filename and every source file under
corpus/ was generated by this script from the fixed seed below. Re-running
it reproduces the tree byte for byte.

What that costs: the point estimates on the Agent Lab page - how many links
resolve only case-insensitively, how many quotes survive whitespace
normalisation, the base rate - are properties of THIS tree and would move on
a real one. What transfers is the shape: that the three option flags
disagree with each other at all, and by roughly how much, is a consequence
of markdown and of filesystems, not of the draw.

What is NOT invented: the defects were not placed to hit a target. The
generator draws each reference from a distribution, writes it, and the
counts on the page are whatever the draw produced - measured afterwards by
running the tool, never typed in by hand.

    python make_corpus.py          # rewrites corpus/ from scratch
"""

from __future__ import annotations

import os
import shutil

SEED = 20260083
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "corpus")


class Rng:
    """xorshift32 - thirty lines of arithmetic, identical in every language,
    which matters because the browser port of this project has to reproduce
    the same corpus."""

    def __init__(self, seed: int):
        self.x = (seed & 0xFFFFFFFF) or 1

    def next(self) -> int:
        x = self.x
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        self.x = x & 0xFFFFFFFF
        return self.x

    def rand(self) -> float:
        return self.next() / 4294967296.0

    def pick(self, seq):
        return seq[self.next() % len(seq)]

    def chance(self, p: float) -> bool:
        return self.rand() < p

    def between(self, lo, hi):
        return lo + self.next() % (hi - lo + 1)


