def build_sources():
    """Return {path: (text, [(name, start_line, end_line), ...])}."""
    out = {}
    for i, path in enumerate(SRC_FILES):
        lines = [HEADER[0] % os.path.basename(path)] + HEADER[1:]
        ranges = []
        for k in range(2):
            sig, body = FUNCS[(i * 2 + k) % len(FUNCS)]
            start = len(lines) + 1
            lines.append(sig)
            lines.extend(body)
            ranges.append((sig.split("(")[0][4:], start, len(lines)))
            lines.append("")
            lines.append("")
        out[path] = ("\n".join(lines).rstrip("\n") + "\n", ranges)
    return out


