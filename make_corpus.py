def relpath(from_dir: str, to_path: str) -> str:
    a = [p for p in from_dir.split("/") if p]
    b = to_path.split("/")
    i = 0
    while i < len(a) and i < len(b) - 1 and a[i] == b[i]:
        i += 1
    return "/".join([".."] * (len(a) - i) + b[i:])


def build():
    rng = Rng(SEED)
    sources = build_sources()

    # ---- pass 1: decide every note's path and headings -------------------
    notes = []
    used = set()
    for topic in TOPICS:
        d = rng.pick(DIRS)
        path = "%s/%s.md" % (d, topic)
        if path.lower() in used:
            continue
        used.add(path.lower())
        n = rng.between(2, 4)
        heads = []
        for _ in range(n):
            for _try in range(6):
                h = rng.pick(HEADINGS)
                if h not in heads:
                    break
            heads.append(h)
        # a repeated heading, sometimes - GitHub gives the second one a -1
        # suffix and a naive checker gives it nothing
        if rng.chance(0.3):
            heads.append(rng.pick(heads))
        notes.append({"path": path, "dir": path.rsplit("/", 1)[0],
                      "title": topic.replace("-", " ").title(),
                      "heads": heads})

    # ---- pass 2: write bodies --------------------------------------------
    files = {}
    for note in notes:
        out = ["# " + note["title"], "", rng.pick(SENTENCES), ""]
        for h in note["heads"]:
            out.append("## " + h)
            out.append("")
            out.append(rng.pick(SENTENCES))

            # links
            for _ in range(rng.between(0, 2)):
                out.append(_link_line(rng, note, notes))

            # a quoted block, sometimes
            if rng.chance(0.30):
                out.append("")
                out.extend(_quote_block(rng, note, sources))
            out.append("")
        files[note["path"]] = "\n".join(out).rstrip("\n") + "\n"

    for path, (text, _ranges) in sources.items():
        files[path] = text
    return files


def _link_line(rng, note, notes):
    other = rng.pick([n for n in notes if n["path"] != note["path"]])
    label = rng.pick(["see the notes", "background", "the other note",
                      "context", "details", "where this came from"])

    roll = rng.rand()
    if roll < 0.18:
        # a file that was renamed and never chased down
        target = relpath(note["dir"], rng.pick(GHOST_FILES))
    elif roll < 0.38:
        # written in lowercase. On NTFS this is fine. On ext4 it is a 404.
        target = relpath(note["dir"], other["path"]).lower()
    else:
        target = relpath(note["dir"], other["path"])

    if rng.chance(0.45):
        if rng.chance(0.80):
            heading = rng.pick(other["heads"])
        else:
            heading = rng.pick(GHOST_HEADINGS)
        target += "#" + (_slug(heading) if rng.chance(0.6) else _raw(heading))

    return "- [%s](%s)" % (label, target)


def _slug(text):
    s = text.strip().lower()
    keep = "abcdefghijklmnopqrstuvwxyz0123456789 _-"
    return "".join(c for c in s if c in keep).replace(" ", "-")


def _raw(text):
    return "-".join(text.strip().lower().split())


def _quote_block(rng, note, sources):
    path = rng.pick(SRC_FILES)
    _name, start, end = rng.pick(sources[path][1])
    body = sources[path][0].split("\n")[start - 1:end]
    rel = relpath(note["dir"], path)

    roll = rng.rand()
    if roll < 0.06:
        rel = relpath(note["dir"], "src/" + rng.pick(["legacy.py", "shapes.py"]))
    elif roll < 0.13:
        end = end + rng.between(3, 25)      # the file got shorter
    elif roll < 0.33:
        # whitespace only: re-indented when it was pasted, or a trailing space
        if rng.chance(0.5):
            body = ["  " + b if b.strip() else b for b in body]
        else:
            body = [b + " " if b.strip() else b for b in body]
    elif roll < 0.55:
        # the source actually changed after this was pasted
        k = rng.next() % len(body)
        body = list(body)
        body[k] = body[k].replace("return", "yield", 1) if "return" in body[k] \
            else body[k].rstrip() + "  # TODO"

    return ["<!-- from: %s#L%d-L%d -->" % (rel, start, end), "```python"] + body + ["```"]


def main():
    files = build()
    if os.path.isdir(ROOT):
        shutil.rmtree(ROOT)
    for rel, text in sorted(files.items()):
        full = os.path.join(ROOT, rel.replace("/", os.sep))
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print("wrote %d files under %s (seed %d)" % (len(files), ROOT, SEED))


if __name__ == "__main__":
    main()
